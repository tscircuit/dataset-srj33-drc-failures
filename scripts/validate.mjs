import assert from 'node:assert/strict'
import { readFileSync, readdirSync } from 'node:fs'
import { createHash } from 'node:crypto'
import samples from '../index.js'
const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url))
const sha = (bytes) => createHash('sha256').update(bytes).digest('hex')
const manifest = JSON.parse(read('manifest.json'))
const audit = JSON.parse(read('audit/candidates.json'))
assert.equal(Object.keys(samples).length, manifest.sampleCount)
assert.deepEqual(Object.keys(samples), manifest.samples.map(s => s.id))
assert.equal(audit.length, manifest.candidateCount)
const benchmarkBytes = read(manifest.pipeline9Filter.resultFile)
assert.equal(sha(benchmarkBytes), manifest.pipeline9Filter.resultSha256)
const benchmark = JSON.parse(benchmarkBytes)
const retained = benchmark.snapshots.filter(s => s.drcErrorCount > 0)
const originalSamples = manifest.samples.filter(s => !s.additionalCandidateId)
assert.deepEqual(originalSamples.map(s => s.id), retained.map(s => s.scenarioName))
assert.equal(retained.reduce((sum, s) => sum + s.drcErrorCount, 0), 150)
assert.equal(audit.filter(c => c.status === 'included').length, originalSamples.length)
let additions = []
if (manifest.additionalAudit) {
  const summaryBytes = read(manifest.additionalAudit.summaryFile)
  assert.equal(sha(summaryBytes), manifest.additionalAudit.summarySha256)
  const summary = JSON.parse(summaryBytes)
  assert.equal(summary.length, manifest.additionalAudit.candidateCount)
  const discoveryBytes = read(manifest.additionalAudit.discovery.summaryFile)
  assert.equal(sha(discoveryBytes), manifest.additionalAudit.discovery.summarySha256)
  const discovered = JSON.parse(discoveryBytes).filter(c => c.status === 'qualifies')
  assert.deepEqual(summary.map(c => c.id), discovered.map(c => c.id))
  additions = summary.filter(s => s.status === 'qualifies')
  assert.equal(additions.length, manifest.additionalAudit.addedSampleCount)
  assert.deepEqual(manifest.samples.filter(s => s.additionalCandidateId).map(s => s.additionalCandidateId), additions.map(s => s.id))
  assert.equal(sha(read('scripts/pipeline9-runtime.bun.lock')), manifest.additionalAudit.runtimeLockSha256)
}
assert.equal(manifest.sampleCount, originalSamples.length + additions.length)
const hashes = new Set()
for (const [i, sample] of manifest.samples.entries()) {
  if (i) assert(manifest.samples[i-1].id < sample.id)
  for (const kind of ['input', 'routed', 'evidence']) assert.equal(sha(read(sample[kind])), sample[`${kind}Sha256`])
  if (sample.additionalCandidateId) {
    const candidate = additions.find(c => c.id === sample.additionalCandidateId)
    assert(candidate && candidate.solved === true && candidate.failed === false)
    assert(candidate.traceCount > 0 && candidate.drcErrorCount > 0)
    assert.equal(sample.baselinePipeline, 9)
    assert.equal(sample.sourceUrl, candidate.sourceUrl)
    assert.equal(sample.sourceJsonPath, candidate.sourceJsonPath)
    assert.equal(sample.inputSha256, candidate.inputSha256)
    assert.equal(sample.pipeline9Benchmark.drcErrorCount, candidate.drcErrorCount)
    assert.equal(sample.drcErrorCount, candidate.drcErrorCount)
  } else {
    const source = audit.find(c => c.sampleId === sample.id)
    assert(source && source.status === 'included')
    assert.equal(source.issue, sample.issueNumber)
    assert.equal(source.url, sample.issueUrl)
    if (source.sourceUrl) assert.equal(source.sourceUrl, sample.sourceUrl)
    const measured = retained.find(s => s.scenarioName === sample.id)
    assert.deepEqual(sample.pipeline9Benchmark, measured)
  }
  assert(sample.pipeline9Benchmark.drcErrorCount > 0 && sample.pipeline9Benchmark.relaxedDrcPassed === false)
  const input = samples[sample.id]
  assert.deepEqual(input, JSON.parse(read(sample.input)))
  assert(Array.isArray(input.connections) && input.connections.length > 0)
  assert(Array.isArray(input.obstacles))
  assert(Number.isInteger(input.layerCount) && input.layerCount > 0)
  for (const n of Object.values(input.bounds)) assert(Number.isFinite(n))
  const routed = JSON.parse(read(sample.routed))
  const evidence = JSON.parse(read(sample.evidence))
  assert(evidence.solved && !evidence.failed && !evidence.error)
  assert(evidence.traceCount > 0 && evidence.drcErrorCount > 0)
  assert.equal(evidence.traceCount, evidence.routedTraces.length)
  assert.equal(evidence.errors.length, sample.drcErrorCount)
  assert.equal(evidence.drcErrorCount, sample.drcErrorCount)
  const { traces: originalTraces, ...inputContext } = input
  const { traces, ...routedContext } = routed
  assert.deepEqual(routedContext, inputContext)
  const replacements = new Set(evidence.routedTraces.map(t => t.__replaces_pcb_trace_id).filter(Boolean))
  assert.deepEqual(traces, [...(originalTraces ?? []).filter(t => !replacements.has(t.pcb_trace_id)), ...evidence.routedTraces])
  assert(!hashes.has(sample.inputSha256), `${sample.id}: duplicate input`)
  hashes.add(sample.inputSha256)
}
assert.equal(hashes.size, manifest.uniqueInputCount)
for (const folder of ['samples', 'routed', 'evidence']) assert.equal(readdirSync(new URL(`../${folder}`, import.meta.url)).length, manifest.sampleCount)
console.log(`Validated ${manifest.sampleCount} distinct SRJs with ${manifest.samples.reduce((sum,s) => sum+s.pipeline9Benchmark.drcErrorCount,0)} Pipeline 9 selection errors.`)
